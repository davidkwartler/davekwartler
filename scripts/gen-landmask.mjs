// Rasterize world countries GeoJSON into a 720x360 land bitmask for the
// /travel map. Fetch input first:
//   curl -sLO https://raw.githubusercontent.com/johan/world.geo.json/master/countries.geo.json
// then: node scripts/gen-landmask.mjs (run from scripts/), output land-mask.ts
// goes to src/data/.
// emitted as a base64 string in a TS module.
import { readFileSync, writeFileSync } from "node:fs";

const W = 720;
const H = 360;
const geo = JSON.parse(
  readFileSync(new URL("./countries.geo.json", import.meta.url), "utf8")
);

// Collect all rings with bounding boxes. Even-odd rule across a polygon's
// rings handles holes.
const polys = []; // { rings: [[x,y]...][], bbox }
function addPolygon(coords) {
  const rings = coords;
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const ring of rings) {
    for (const [x, y] of ring) {
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
  }
  polys.push({ rings, bbox: [minX, minY, maxX, maxY] });
}
for (const f of geo.features) {
  const g = f.geometry;
  if (!g) continue;
  if (g.type === "Polygon") addPolygon(g.coordinates);
  else if (g.type === "MultiPolygon") g.coordinates.forEach(addPolygon);
}

function inRing(ring, px, py) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > py !== yj > py && px < ((xj - xi) * (py - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

function isLand(lon, lat) {
  for (const { rings, bbox } of polys) {
    if (lon < bbox[0] || lon > bbox[2] || lat < bbox[1] || lat > bbox[3]) continue;
    let count = 0;
    for (const ring of rings) if (inRing(ring, lon, lat)) count++;
    if (count % 2 === 1) return true;
  }
  return false;
}

const bytes = new Uint8Array(Math.ceil((W * H) / 8));
let landCells = 0;
for (let j = 0; j < H; j++) {
  const lat = 90 - ((j + 0.5) * 180) / H;
  for (let i = 0; i < W; i++) {
    const lon = -180 + ((i + 0.5) * 360) / W;
    if (isLand(lon, lat)) {
      const bit = j * W + i;
      bytes[bit >> 3] |= 1 << (bit & 7);
      landCells++;
    }
  }
}
console.log(`land cells: ${landCells}/${W * H} (${((landCells / (W * H)) * 100).toFixed(1)}%)`);

const b64 = Buffer.from(bytes).toString("base64");
const out = `// Generated by scripts (gen-landmask.mjs) from world countries GeoJSON
// (johan/world.geo.json, public domain). 720x360 equirectangular land
// bitmask, row-major from lat +90 to -90, lon -180 to +180, LSB-first
// within each byte. Decode with landMaskAt() below.

export const LAND_W = ${W};
export const LAND_H = ${H};

const LAND_B64 =
${b64.match(/.{1,76}/g).map((s) => `  "${s}"`).join(" +\n")};

let bytes: Uint8Array | null = null;

function decode(): Uint8Array {
  if (bytes) return bytes;
  const bin = atob(LAND_B64);
  bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return bytes;
}

/** True if the given lon/lat falls on land. */
export function landAt(lon: number, lat: number): boolean {
  const i = Math.min(LAND_W - 1, Math.max(0, Math.floor(((lon + 180) / 360) * LAND_W)));
  const j = Math.min(LAND_H - 1, Math.max(0, Math.floor(((90 - lat) / 180) * LAND_H)));
  const bit = j * LAND_W + i;
  return (decode()[bit >> 3] & (1 << (bit & 7))) !== 0;
}
`;
writeFileSync(new URL("./land-mask.ts", import.meta.url), out);
console.log("wrote land-mask.ts", out.length, "chars");
